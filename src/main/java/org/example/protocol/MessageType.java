package org.example.protocol;

/**
 * Типы сообщений клиент-серверного протокола мессенджера ICQ.
 *
 * <p>Один {@link Message} всегда имеет ровно один тип. По типу сервер и клиент
 * понимают, как обрабатывать сообщение (вход, доставка, служебные события).
 *
 * <p>Закладываем сразу весь набор, чтобы на ПР4 (XML-протокол) и ПР5
 * (статусы, индикатор «печатает…») не пришлось расширять протокол и
 * переписывать обработчики.
 */
public enum MessageType {

    /**
     * Клиент → сервер: запрос на вход (ник в {@code from}, пароль в {@code body}).
     * Пароль на ПР12 идёт открытым текстом — канал шифруется отдельным ПР (TLS).
     */
    LOGIN,
    /** Сервер → клиент: вход разрешён. */
    LOGIN_OK,
    /** Сервер → клиент: вход отклонён (нет учётки/неверный пароль), причина в {@code body}. */
    LOGIN_FAIL,

    /**
     * Клиент → сервер: регистрация новой учётки (ник в {@code from}, пароль в
     * {@code body}). Отдельное действие от {@link #LOGIN}: так опечатка в нике
     * даёт честную ошибку «ник занят»/«неверный пароль», а не молча создаёт
     * новый аккаунт.
     */
    REGISTER,
    /** Сервер → клиент: учётка создана (можно входить). */
    REGISTER_OK,
    /** Сервер → клиент: регистрация отклонена (ник занят/невалиден), причина в {@code body}. */
    REGISTER_FAIL,

    /**
     * Обычное текстовое сообщение. {@code to}: {@code null}/{@code "*"} — всем
     * (общий чат), ник — личное, {@code "#имя"} — в комнату (ПР16).
     */
    MESSAGE,

    /**
     * Групповые чаты (ПР16). Комната адресуется как {@code "#имя"} в поле
     * {@code to} (см. {@link org.example.protocol.Message#isRoom()}).
     */
    /** Клиент → сервер: войти в комнату {@code to=#имя} (создаётся, если её ещё нет). */
    ROOM_JOIN,
    /** Клиент → сервер: покинуть комнату {@code to=#имя}. */
    ROOM_LEAVE,
    /**
     * Список комнат. Клиент → сервер — запрос (поля пустые); сервер → клиент —
     * ответ/пуш: {@code body} = имена комнат через запятую.
     */
    ROOM_LIST,
    /**
     * Сервер → клиент: участники комнаты {@code to=#имя}, {@code body} = ники
     * через запятую. Шлётся членам комнаты при входе и при изменении состава.
     */
    ROOM_MEMBERS,

    /**
     * Квитанция «доставлено» (ПР14). Сервер → отправителю: его личное сообщение
     * {@code id} (атрибут {@link org.example.server.store.MessageStore#ATTR_ID})
     * дошло до адресата — сразу при живой доставке или при дренаже оффлайн-очереди,
     * когда адресат вошёл. Отправитель рисует одну галочку ✓.
     */
    DELIVERED,
    /**
     * Квитанция «прочитано» (ПР14). Двунаправленная: клиент-читатель →
     * серверу шлёт {@code READ to=собеседник}, когда открыл с ним диалог; сервер
     * помечает соответствующие сообщения и пересылает {@code READ} их
     * отправителю ({@code from=читатель, to=отправитель}). Отправитель рисует ✓✓.
     */
    READ,

    /** Сервер → клиент: актуальный список онлайн-пользователей ({@code body}). */
    USER_LIST,
    /** Сервер → клиент: пользователь зашёл (ник в {@code body}). */
    USER_JOINED,
    /** Сервер → клиент: пользователь вышел (ник в {@code body}). */
    USER_LEFT,

    /**
     * Начало передачи файла (ПР15). Клиент → серверу при загрузке, сервер →
     * клиенту при скачивании. Атрибуты: {@code ref} (хэндл передачи), {@code name},
     * {@code size}, {@code mime}; при загрузке адресат — в поле {@code to}.
     */
    FILE_START,
    /** Очередной чанк файла: {@code ref} в атрибуте, Base64-данные в {@code body}. */
    FILE_CHUNK,
    /** Конец передачи файла: {@code ref} в атрибуте. */
    FILE_END,
    /** Клиент → серверу: запрос на скачивание файла {@code fileId} (атрибут). */
    FILE_GET,

    /** Уведомление «пользователь печатает…». */
    TYPING,

    /** Служебная ошибка протокола/сервера, текст в {@code body}. */
    ERROR,

    /** Проверка живости соединения (keep-alive). */
    PING,

    /** Ответ на {@link #PING}: подтверждает, что вторая сторона жива. */
    PONG
}
